// A browser can refuse storage access (private mode). The app then works with the default language.
const stored = key => { try { return localStorage.getItem(key); } catch { return null; } };

// English is the default on each phone. The language button changes it, and the phone keeps the choice.
export const lang = stored('lang') === 'sr' ? 'sr' : 'en';

// Text for a key, with {name} parts filled in. Returns undefined for an unknown key.
export function t(key, vars = {}) {
  const text = TEXT[lang][key] ?? TEXT.en[key];
  return text === undefined ? undefined : text.replace(/\{(\w+)\}/g, (part, name) => vars[name] ?? part);
}

// Fills each element that names a text key: data-t (content), data-t-placeholder, data-t-label.
export function applyText(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t) ?? el.textContent;
  for (const el of root.querySelectorAll('[data-t-placeholder]')) el.placeholder = t(el.dataset.tPlaceholder) ?? '';
  for (const el of root.querySelectorAll('[data-t-label]')) el.setAttribute('aria-label', t(el.dataset.tLabel) ?? '');
}

export function switchLang() {
  try { localStorage.setItem('lang', lang === 'sr' ? 'en' : 'sr'); } catch { /* no storage: the switch does nothing */ }
  location.reload();
}
